package com.java.standard.edition.math;

public class MathDemo 
{
	public static void main(String[] args) 
	{
		System.out.println(Math.max(90, 10));//90
		System.out.println(Math.min(32, 90));//32
		System.out.println(Math.sqrt(25));//5.0
		System.out.println(Math.ceil(65.1));//66.0
		System.out.println(Math.floor(65.9));//65.0
		System.out.println(Math.round(75.5));//76
		System.out.println(Math.abs(-100));//100
		System.out.println(Math.random());//some random number
		
	}

}
