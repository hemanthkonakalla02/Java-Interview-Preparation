package com.java.standard.edition.aggregationcomposition;

public class Charger 
{
	private String color;
	private int cost;
	
	public Charger(String color,int cost)
	{
		this.color=color;
		this.cost=cost;
	}

	public String getColor() {
		return color;
	}

	public int getCost() {
		return cost;
	}
	
	

}
